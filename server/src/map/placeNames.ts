/** count 개 지명 (seed 결정론, 고유). count 가 풀보다 크면 "이름 2" 꼴로 접미사를 붙여 고유성을 지킨다 */
export function assignPlaceNames(seed: number, count: number): string[] {
  const pool = PLACE_NAME_POOL.slice();
  const rng = new Mulberry32((seed ^ 0x5a17c0de) >>> 0);
  // Fisher–Yates (정수 나머지 — 편향은 표시용이라 무시)
  for (let i = pool.length - 1; i > 0; i--) {
    const j = rng.nextU32() % (i + 1);
    const x = pool[i];
    pool[i] = pool[j];
    pool[j] = x;
  }
  const out: string[] = [];
  for (let i = 0; i < count; i++) {
    const k = Math.floor(i / pool.length);
    out.push(k === 0 ? pool[i % pool.length] : `${pool[i % pool.length]} ${k + 1}`);
  }
  return out;
}
